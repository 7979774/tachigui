#!/usr/bin/env python3
"""apk v2 形式 (apk-tools 3 でも --allow-untrusted で導入可) の noarch パッケージを作る。

使い方: python mkapk2.py <version> <rootdir> <scriptsdir> <outdir>
"""
import gzip
import hashlib
import io
import os
import sys
import tarfile
import time

NAME = 'tachigui'
DESC = 'TachiGUI - standalone router web UI (setup, status, IPv6) served at /'
DEPENDS = ['uhttpd', 'uhttpd-mod-ubus', 'rpcd', 'rpcd-mod-file', 'rpcd-mod-luci', 'rpcd-mod-ucode', 'ucode-mod-uci', 'ucode-mod-ubus', 'ucode-mod-fs', 'luci-base', 'cgi-io', 'jsonfilter']
LICENSE = 'MIT'


def tar_bytes(entries, finish, fmt=tarfile.GNU_FORMAT):
    """entries: [(TarInfo, bytes|None)]。finish=False なら終端ブロックを付けない (apk の制御部)。"""
    bio = io.BytesIO()
    tf = tarfile.TarFile(fileobj=bio, mode='w', format=fmt)
    for ti, data in entries:
        tf.addfile(ti, io.BytesIO(data) if data is not None else None)
    if finish:
        tf.close()
    return bio.getvalue()


def gz(data):
    out = io.BytesIO()
    with gzip.GzipFile(fileobj=out, mode='wb', mtime=0, compresslevel=9) as g:
        g.write(data)
    return out.getvalue()


def mkinfo(name, mode, data=None, typ=tarfile.REGTYPE, mtime=0):
    ti = tarfile.TarInfo(name)
    ti.mode = mode
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = 'root'
    ti.mtime = mtime
    ti.type = typ
    ti.size = len(data) if data is not None else 0
    return ti


VERSION = ''


def bust(data):
    """自前の JS の import に ?v=<版> を付ける (ブラウザが古い部品を使い続けないように)。
    vendor (Preact など) は、中で互いに読み合うため、付けない (付けると、別の URL になり、二重に読み込まれる)。"""
    import re
    def add(m):
        return m.group(0) if '/vendor/' in m.group(1) else m.group(1) + '?v=' + VERSION + m.group(2)
    t = data.decode('utf-8')
    t = re.sub(r"(from\s+'\.{1,2}/[^']*?\.js)(')", add, t)
    t = re.sub(r"(import\('\.{1,2}/[^']*?\.js)('\))", add, t)
    return t.encode('utf-8')


def collect(root, mtime):
    entries, size = [], 0
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        rel = os.path.relpath(dirpath, root).replace(os.sep, '/')
        if rel != '.':
            entries.append((mkinfo(rel, 0o755, typ=tarfile.DIRTYPE, mtime=mtime), None))
        for fn in sorted(filenames):
            full = os.path.join(dirpath, fn)
            with open(full, 'rb') as f:
                data = f.read()
            if fn.endswith(('.js', '.json', '.uc')) or 'ucode' in rel or (rel.startswith('usr/libexec') or rel.startswith('etc/hotplug.d')):
                data = data.replace(b'\r\n', b'\n')
            if fn.endswith('.js') and rel.startswith('www/ui/js') and '/vendor' not in rel:
                data = bust(data)
            rp = (rel + '/' + fn) if rel != '.' else fn
            ti = mkinfo(rp, 0o755 if (rel.startswith('usr/libexec') or rel.startswith('etc/hotplug.d')) else 0o644, data, mtime=mtime)
            ti.pax_headers = {'APK-TOOLS.checksum.SHA1': hashlib.sha1(data).hexdigest()}
            entries.append((ti, data))
            size += len(data)
    return entries, size


def main():
    ver, root, scripts, outdir = sys.argv[1:5]
    global VERSION
    VERSION = ver
    now = int(time.time())

    data_entries, size = collect(root, now)
    data_gz = gz(tar_bytes(data_entries, True, tarfile.PAX_FORMAT))
    datahash = hashlib.sha256(data_gz).hexdigest()

    lines = [
        '# Generated by mkapk2.py',
        'pkgname = %s' % NAME,
        'pkgver = %s' % ver,
        'pkgdesc = %s' % DESC,
        'url = ',
        'builddate = %d' % now,
        'packager = tachigui',
        'size = %d' % size,
        'arch = noarch',
        'origin = %s' % NAME,
        'license = %s' % LICENSE,
    ] + ['depend = %s' % d for d in DEPENDS] + ['datahash = %s' % datahash]
    pkginfo = ('\n'.join(lines) + '\n').encode()

    ctl = [(mkinfo('.PKGINFO', 0o644, pkginfo, mtime=now), pkginfo)]
    for fname, apkname in (('post-install', '.post-install'), ('post-install', '.post-upgrade'), ('post-remove', '.post-deinstall')):
        with open(os.path.join(scripts, fname), 'rb') as f:
            sd = f.read().replace(b'\r\n', b'\n')
        ctl.append((mkinfo(apkname, 0o755, sd, mtime=now), sd))
    ctl_gz = gz(tar_bytes(ctl, False))

    out = os.path.join(outdir, '%s-%s.apk' % (NAME, ver))
    with open(out, 'wb') as f:
        f.write(ctl_gz + data_gz)
    print(out, os.path.getsize(out), 'bytes; data files:', len([e for e in data_entries if e[1] is not None]))


if __name__ == '__main__':
    main()
